  [PUSH_EVENTS.AUTH_WELCOME]: PUSH_CATEGORIES.AUTH,
  [PUSH_EVENTS.AUTH_PASSWORD_RESET]: PUSH_CATEGORIES.AUTH,
  [PUSH_EVENTS.AUTH_ACCOUNT_LOCKED]: PUSH_CATEGORIES.AUTH,
  [PUSH_EVENTS.AUTH_ACCOUNT_UNLOCKED]: PUSH_CATEGORIES.AUTH,
  [PUSH_EVENTS.JOB_PUBLISHED]: PUSH_CATEGORIES.MARKETPLACE,
  [PUSH_EVENTS.TECHNICIAN_APPLIED]: PUSH_CATEGORIES.MARKETPLACE,
  [PUSH_EVENTS.TECHNICIAN_ASSIGNED]: PUSH_CATEGORIES.MARKETPLACE,
