  [PUSH_EVENTS.JOB_STATUS]: PUSH_CATEGORIES.MARKETPLACE,
  [PUSH_EVENTS.MESSAGE_NEW]: PUSH_CATEGORIES.MESSAGING,
  [PUSH_EVENTS.MESSAGE_MENTION]: PUSH_CATEGORIES.MESSAGING,
  [PUSH_EVENTS.MESSAGE_ATTACHMENT]: PUSH_CATEGORIES.MESSAGING,
